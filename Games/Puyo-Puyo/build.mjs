#!/usr/bin/env node
/**
 * "Build" for a dependency-free static game: copy src/ to dist/, then bundle
 * shared/synthAudio.ts and shared/juice.ts into IIFEs that plain JS bridges onto.
 * There is no full Vite/React stack here; BASE_URL rewriting is unnecessary
 * because every asset reference in src/index.html is already relative.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(dirname, 'src');
const outDir = path.join(dirname, 'dist');
const require = createRequire(path.resolve(dirname, '../../package.json'));
const sharedRoot = path.dirname(require.resolve('@clubhouse/shared/package.json'));
const sharedSynth = path.join(sharedRoot, 'synthAudio.ts');
const sharedJuice = path.join(sharedRoot, 'juice.ts');
const bundledSynthRel = path.join('js', 'clubhouse-synth-audio.js');
const bundledJuiceRel = path.join('js', 'clubhouse-juice.js');

function copyRecursive(src, dest) {
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    fs.mkdirSync(dest, { recursive: true });
    for (const name of fs.readdirSync(src)) {
      copyRecursive(path.join(src, name), path.join(dest, name));
    }
    return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

async function bundleSharedSynthAudio(destFile) {
  const esbuild = require('esbuild');
  const banner =
    '/* Generated by build.mjs from @clubhouse/shared/synthAudio — do not edit. */\n';
  await esbuild.build({
    entryPoints: [sharedSynth],
    outfile: destFile,
    bundle: true,
    format: 'iife',
    globalName: 'ClubhouseSynthAudio',
    platform: 'browser',
    target: ['es2018'],
    banner: { js: banner },
    logLevel: 'silent',
  });
}

/**
 * Bundle juice without pulling a second copy of synthAudio — Puyo already owns
 * audio via ClubhouseSynthAudio / PuyoAudio. hit() audio calls become no-ops.
 */
async function bundleSharedJuice(destFile) {
  const esbuild = require('esbuild');
  const banner =
    '/* Generated by build.mjs from @clubhouse/shared/juice — do not edit. */\n';
  const stubPlugin = {
    name: 'stub-synth-audio',
    setup(build) {
      build.onResolve({ filter: /synthAudio/ }, () => ({
        path: 'clubhouse-synth-audio-stub',
        namespace: 'stub',
      }));
      build.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
        contents: [
          'export function playCombo() {}',
          'export function playError() {}',
          'export function playImpact() {}',
          'export function playMove() {}',
          'export function playWin() {}',
        ].join('\n'),
        loader: 'js',
      }));
    },
  };
  await esbuild.build({
    entryPoints: [sharedJuice],
    outfile: destFile,
    bundle: true,
    format: 'iife',
    globalName: 'ClubhouseJuice',
    platform: 'browser',
    target: ['es2018'],
    banner: { js: banner },
    plugins: [stubPlugin],
    logLevel: 'silent',
  });
}

if (!fs.existsSync(srcDir)) {
  console.error('Missing src/ directory');
  process.exit(1);
}
if (!fs.existsSync(sharedSynth)) {
  console.error('Missing shared/synthAudio.ts at', sharedSynth);
  process.exit(1);
}
if (!fs.existsSync(sharedJuice)) {
  console.error('Missing shared/juice.ts at', sharedJuice);
  process.exit(1);
}

// Refresh bridge bundles in src/ first so copy picks them up for dist/.
await bundleSharedSynthAudio(path.join(srcDir, bundledSynthRel));
await bundleSharedJuice(path.join(srcDir, bundledJuiceRel));

fs.rmSync(outDir, { recursive: true, force: true });
copyRecursive(srcDir, outDir);

console.log('Puyo Puyo: copied src/ -> dist/ + bundled shared synthAudio + juice');
