#!/usr/bin/env node
/**
 * Bundle @clubhouse/shared/originLoreDom + WALL_FLIP_LORE into a static IIFE
 * (`origin-lore.js`) so Wall-Flip works offline and from file:// with zero CDN.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const gameRoot = path.resolve(dirname, '..');
const repoRoot = path.resolve(gameRoot, '../..');
const sharedRoot = path.join(repoRoot, 'shared');
const sharedOriginLore = path.join(sharedRoot, 'originLoreDom.ts');
const sharedVanillaLore = path.join(sharedRoot, 'lore', 'vanillaDom.ts');
const outFile = path.join(gameRoot, 'origin-lore.js');

if (!fs.existsSync(sharedOriginLore) || !fs.existsSync(sharedVanillaLore)) {
  console.error('Missing shared/originLoreDom.ts or shared/lore/vanillaDom.ts');
  process.exit(1);
}

const require = createRequire(path.join(repoRoot, 'package.json'));
const esbuild = require('esbuild');

const banner =
  '/* Generated by scripts/build-origin-lore.mjs from @clubhouse/shared/originLoreDom + lore/vanillaDom — do not edit. */\n';

const entryContents = [
  `import { openOriginLoreModal, mountOriginLoreTrigger, createOriginLoreTrigger } from ${JSON.stringify(sharedOriginLore)};`,
  `import { WALL_FLIP_LORE } from ${JSON.stringify(sharedVanillaLore)};`,
  `export { openOriginLoreModal, mountOriginLoreTrigger, createOriginLoreTrigger, WALL_FLIP_LORE };`,
  `export function open(opts = {}) { return openOriginLoreModal({ dossier: WALL_FLIP_LORE, ...opts }); }`,
].join('\n');

await esbuild.build({
  stdin: {
    contents: entryContents,
    resolveDir: sharedRoot,
    loader: 'ts',
  },
  outfile: outFile,
  bundle: true,
  format: 'iife',
  globalName: 'WallFlipOriginLore',
  platform: 'browser',
  target: ['es2018'],
  banner: { js: banner },
  logLevel: 'silent',
});

console.log('Wall-Flip: built origin-lore.js from shared/originLoreDom + WALL_FLIP_LORE');
